"use strict";
// move-engine PILOT: Gunblade's three approved moves (moves/sonic-katar/gunblade.js, the same file the Sonic Katar mockup page
// runs) → the game's animation scripts, written into the migration's generated module.
//   node tools/move-engine/build/pilot-gunblade.js [--refresh-assets]
//     → modules/fabula-ultima-companion/data-migrations/_gunblade-move-engine-anims.js
//   --refresh-assets re-reads the page's meta.json on E: and rewrites moves/sonic-katar/assets.json (the Forge URLs + clip
//   sizes the build uses), so a normal build needs nothing outside the repo.
const fs = require("fs");
const path = require("path");
const GB = require("./game-build.js");
const ROOT = path.join(__dirname, "..");
const FAM = path.join(ROOT, "moves", "sonic-katar");
const OUT = path.join(ROOT, "..", "..", "modules", "fabula-ultima-companion", "data-migrations", "_gunblade-move-engine-anims.js");
const rd = (p) => fs.readFileSync(p, "utf8").replace(/\r\n/g, "\n");

const files = [{ name: "moves/sonic-katar/head.js", text: rd(path.join(FAM, "head.js")) }, { name: "moves/sonic-katar/gunblade.js", text: rd(path.join(FAM, "gunblade.js")) }];
const ASSETS_JSON = path.join(FAM, "assets.json");
if (process.argv.includes("--refresh-assets") || !fs.existsSync(ASSETS_JSON)) {
  const meta = JSON.parse(rd("E:/Art(New Com)/DND/Fabula Ultima/Resource/Animation/Sonic Katar/src/assets/meta.json"));
  const all = files.map((f) => f.text).concat(GB.ORDER.map((p) => rd(path.join(ROOT, p)))).join("\n");
  const RO = "Sound/Ragnarok Online/";
  const a = GB.assetsFromMeta(meta, { only: all, sfxUrls: { ro_sonicblow: RO + "ro_sonicblow.wav", ro_katar: RO + "ro_attack_katar.wav", ro_katar2: RO + "ro_attack_katar2.wav", ro_hitdagger: RO + "ro_hit_dagger.wav" } });
  if (a.missing.length) throw new Error("assets without a Forge URL: " + a.missing.join(", "));
  fs.writeFileSync(ASSETS_JSON, JSON.stringify({ note: "Forge URLs + clip sizes for the sonic-katar family (build/pilot-gunblade.js --refresh-assets, from the Sonic Katar page's meta.json)", clips: a.clips, sfx: a.sfx }, null, 1) + "\n");
}
const { clips, sfx } = JSON.parse(rd(ASSETS_JSON));
const assets = { clips, sfx };

// The game hands the move its real Accuracy result (moveResult). The tune below is only the fallback when no outcome comes
// with the action (a bench preview): a plain physical swing / a plain shot, never a fake fire.
const cfg = { partyFoot: 0.97, seed: 2611, totalTimeoutMs: 20000 };
const attack = GB.buildScript({ key: "gb_sword", name: "Gunblade · Attack (Sword / Firearm by form)", files, assets,
  cfg: { ...cfg, tune: { gb_sword: { roll: 2 }, gb_gun: { roll: 1 } } }, playOpts: { byForm: ["gb_sword", "gb_gun"] } });
const transform = GB.buildScript({ key: "gb_tf", name: "Gunblade · Transform", files, assets, cfg,
  playOpts: { variantTune: { gun: { dir: 0 }, sword: { dir: 1 } } } });
for (const [n, r] of [["attack", attack], ["transform", transform]]) {
  if (!r.ok) { console.error(n, r.errors); process.exit(1); }
  console.log(n, r.chars, "chars", r.warnings.length ? "· warnings: " + r.warnings.join("; ") : "");
}
const body = [
  "// GENERATED by tools/move-engine/build/pilot-gunblade.js — do not edit by hand.",
  "// move-engine pilot (2026-11-22): the approved mockup moves gb_sword / gb_gun / gb_tf, run unchanged on the game runtime.",
  "// Source: tools/move-engine/moves/sonic-katar/{head,gunblade}.js (the same files the Sonic Katar mockup page runs).",
  "export const ENGINE_VERSION = " + JSON.stringify(/MOVE_ENGINE_VERSION = "([^"]+)"/.exec(rd(path.join(ROOT, "shared", "core.js")))[1]) + ";",
  "export const GUNBLADE_ATTACK_SCRIPT = " + JSON.stringify(attack.encoded) + ";",
  "export const GUNBLADE_TRANSFORM_SCRIPT = " + JSON.stringify(transform.encoded) + ";",
  // default timing: BD applies damage on oni:animationEnd, which the outer emits at the move's gate (its first hit number)
  "export const SCRIPT_TIMING = { mode: \"default\", offset: \"0\" };",
  "",
].join("\n");
fs.writeFileSync(OUT, body);
console.log("wrote", OUT, (body.length / 1024).toFixed(0) + " KB");

"use strict";
// Spell Fencer: the approved mockup moves (round rmwsrvdn3, page 94H4XUhvbu42SzSYknv5e7 v2) → the game's animation scripts.
//   node tools/move-engine/build/spell-fencer-anims.js
//     → modules/fabula-ultima-companion/data-migrations/_spell-fencer-anims.js (used by 2026-11-23-spell-fencer-anims)
// Same files the mockup page runs (moves/spell-fencer/head.js + rhapsody.js). Assets = ONLY what the approved config plays:
// the pinned pixelfx variants (charge, sigil crown On, unleash Full, braid r1n1c0), 051_powerup_1 and the chosen sounds.
const fs = require("fs");
const path = require("path");
const GB = require("./game-build.js");
const ROOT = path.join(__dirname, "..");
const FAM = path.join(ROOT, "moves", "spell-fencer");
const OUT = path.join(ROOT, "..", "..", "modules", "fabula-ultima-companion", "data-migrations", "_spell-fencer-anims.js");
const rd = (p) => fs.readFileSync(p, "utf8").replace(/\r\n/g, "\n");

// ── APPROVED (round rmwsrvdn3, 2026-11-23): the one constants block. Every other slider = its default in rhapsody.js.
const APPROVED = {
  rhapsody: { stance: 330, charge: 50, sigil: 120, burst: 120, brate: 135,
    radius: 1, notes: 1, pal: 0, crown: 0, dens: 1, csnd: 0, rise: 0, heavy: 0, petal: 0, chime: 0, buff: 0 },
  resonance_gain: {},   // approved as built (round 1)
};
const CLIPS = ["sf_charge", "sf_sigil_k1", "sf_unleash_d1", "sf_braid_r1n1c0"];          // pinned variants (pxfx keys)
const SOUNDS = { rhapsody: ["beginspell", "guard", "wind7", "gacha_crystal", "flower", "bell3", "powerup"], resonance_gain: ["item3"] };

const files = ["head", "rhapsody"].map((f) => ({ name: "moves/spell-fencer/" + f + ".js", text: rd(path.join(FAM, f + ".js")) }));
const all = JSON.parse(rd(path.join(FAM, "assets.json")));
function assetsFor(key) {
  const clips = {}, sfx = {};
  if (key === "rhapsody") {
    for (const c of CLIPS) for (const L of ["back", "front", "light"]) { const k = "px_" + c + "_" + L; if (!all.clips[k]) throw new Error("no clip " + k); clips[k] = all.clips[k]; }
    clips["051_powerup_1"] = all.clips["051_powerup_1"];
  }
  for (const s of SOUNDS[key]) { if (!all.sfx[s]) throw new Error("no sfx " + s); sfx[s] = all.sfx[s]; }
  return { clips, sfx };
}
const cfg = { partyFoot: 0.97, seed: 1123, totalTimeoutMs: 20000 };
const out = {};
for (const key of ["rhapsody", "resonance_gain"]) {
  const r = GB.buildScript({ key, name: "Spell Fencer · " + (key === "rhapsody" ? "Spellblade Rhapsody" : "+1 Resonance"), files, assets: assetsFor(key), cfg: { ...cfg, tune: { [key]: APPROVED[key] } } });
  if (!r.ok) { console.error(key, r.errors); process.exit(1); }
  console.log(key, r.chars, "chars", r.warnings.length ? "· warnings: " + r.warnings.join("; ") : "· no warnings");
  out[key] = r;
}
const body = [
  "// GENERATED by tools/move-engine/build/spell-fencer-anims.js — do not edit by hand.",
  "// The approved Spell Fencer mockup moves (round rmwsrvdn3) run unchanged on the game runtime.",
  "// Source: tools/move-engine/moves/spell-fencer/{head,rhapsody}.js (the same files the mockup page runs).",
  "export const ENGINE_VERSION = " + JSON.stringify(/MOVE_ENGINE_VERSION = "([^"]+)"/.exec(rd(path.join(ROOT, "shared", "core.js")))[1]) + ";",
  "export const RHAPSODY_SCRIPT = " + JSON.stringify(out.rhapsody.encoded) + ";",
  "export const RESONANCE_GAIN_SCRIPT = " + JSON.stringify(out.resonance_gain.encoded) + ";",
  "export const SCRIPT_TIMING = { mode: \"default\", offset: \"0\" };",
  "",
].join("\n");
fs.writeFileSync(OUT, body);
console.log("wrote", OUT, (body.length / 1024).toFixed(0) + " KB");
module.exports = { APPROVED, CLIPS, SOUNDS, assetsFor, files, cfg };

"use strict";
// ============================================================================
// Sonic Katar's Sonic Blow animation (2026-11-21), ported from the approved mockup
// (E:\Art(New Com)\DND\Fabula Ultima\Resource\Animation\Sonic Katar, v2) on oni.timeline (live board).
// Shot = nox-shots/ghoul-hound-kit.inner.js (the melee kit) + sonic-shots/sonic-blow.inner.js, wrapped by
// dungeon-templates.shell(). Every timing / size lives in the shot's constants block, copied from
// spec/sonic-blow-mockup-timeline.json.
//
//   node tools/anim-studio/lib/sonic-signatures.js        → writes modules/.../data-migrations/_sonic-gunblade-anims.js
// The Gunblade attack / transform animations are not ported yet (exports stay empty: the default attack plays).
// ============================================================================
const fs = require("fs");
const path = require("path");
const { shell } = require("./dungeon-templates.js");
const NA = require("./nox-assets.js");
const { encode, validate } = require("./encode.js");

const FORGE = "https://assets.forge-vtt.com/610d918102e7ac281373ffcb/";
const KIT = fs.readFileSync(path.join(__dirname, "nox-shots", "ghoul-hound-kit.inner.js"), "utf8");
const SHOT = fs.readFileSync(path.join(__dirname, "sonic-shots", "sonic-blow.inner.js"), "utf8");

const ASSETS = {
  clips: {
    ro_sonicblow: { url: FORGE + "Animation/Ragnarok%20Online/sonicblow.webm", w: 300, h: 328, dur: 667, ax: 0.4833, ay: 0.6311, k: 1.1, add: false },
    "001_hit_physical": (() => { const c = NA.CLIPS["001_hit_physical"]; return { url: c.url, w: c.w, h: c.h, dur: c.dur, ax: c.ax, ay: c.ay, k: c.k, add: false }; })(),
  },
  sfx: {
    dash: FORGE + "Sound/DashA.wav",
    crit: NA.SFX.crit,
    ro_sonicblow: FORGE + "Sound/Ragnarok%20Online/ro_sonicblow.wav",
    ro_katar: FORGE + "Sound/Ragnarok%20Online/ro_attack_katar.wav",
    ro_katar2: FORGE + "Sound/Ragnarok%20Online/ro_attack_katar2.wav",
    ro_hitdagger: FORGE + "Sound/Ragnarok%20Online/ro_hit_dagger.wav",
  },
};
// gate (offset mode): the first strike, 592.1 + 64.3 ms after the dash (the mockup's markGate)
const GATE = Math.round(592.1 + 64.3);

function sonicBlow() {
  const cfg = { partyFoot: 0.97, volume: 0.75, seed: 2611, totalTimeoutMs: 20000 };
  const script = shell({ key: "sonic-blow", name: "Sonic Blow", cfg, assets: ASSETS, inner: KIT + "\n// ── shot ──\n" + SHOT, timeout: cfg.totalTimeoutMs, startOnReady: true });
  return { script, timing: { mode: "offset", offset: GATE } };
}

if (require.main === module) {
  const sb = sonicBlow();
  const v = validate(sb.script, { chain: 8 });
  if (v && v.ok === false) { console.error("validate failed", v); process.exit(1); }
  const out = path.join(__dirname, "..", "..", "..", "modules", "fabula-ultima-companion", "data-migrations", "_sonic-gunblade-anims.js");
  const body = [
    "// GENERATED by tools/anim-studio/lib/sonic-signatures.js — do not edit by hand.",
    "// Sonic Blow = the approved mockup port (oni.timeline, live board). Gunblade attack / transform: not ported yet.",
    "export const SONIC_BLOW_SCRIPT = " + JSON.stringify(encode(sb.script)) + ";",
    "export const GUNBLADE_ATTACK_SCRIPT = \"\";",
    "export const GUNBLADE_TRANSFORM_SCRIPT = \"\";",
    "export const SCRIPT_TIMING = " + JSON.stringify({ sonicBlow: sb.timing, gunbladeAttack: { mode: "default", offset: 0 }, gunbladeTransform: { mode: "default", offset: 0 } }) + ";",
    "",
  ].join("\n");
  fs.writeFileSync(out, body);
  console.log("wrote", out, sb.script.length, "chars; validate:", JSON.stringify(v).slice(0, 300));
}
module.exports = { sonicBlow, ASSETS, GATE };

"use strict";
// ============================================================================
// Dungeon animation templates — Valley of the Dragon + Fafnir Castle pass.
//
// Each exported template returns a COMPLETE outer animation_script source
// string for one skill, ready to hand to lib/encode.js validate()/encode().
//
// THE TWO STORAGE RULES (both have bitten this codebase before):
//  1. The whole file must contain EXACTLY TWO backticks — the String.raw
//     delimiters wrapping the inner scriptSource. A backtick anywhere else,
//     even inside a // comment, closes the template early and breaks the outer
//     parse. So every inner string here is built with concatenation, never a
//     template literal.
//  2. animation_script is a rich-text field. BD's _stripHtml eats raw < and >,
//     so the stored form is HTML-escaped and <p>-wrapped. encode() handles it.
//
// PACING: durations are deliberately slow and the curves are quad/sine, not
// cubic — easeInOutCubic packs its travel into a short fast middle and reads as
// a whoosh at any duration. Everything lives in CFG so a re-tune is a number
// change, never a code change.
//
// DAMAGE GATE: `donePhase` picks when oni.fireDone() runs — "impact" lands the
// damage on the visual hit, "end" defers it past the whole choreography. The
// Geist pass found BD's RESOLVE triggers a 300-600ms CSB HP recompute per PC,
// which reads as a freeze if it lands mid-motion, so damaging templates default
// to "end" and only shots with a designed impact beat (a whiteout) use
// "impact".
// ============================================================================

/* ── Outer shell ─────────────────────────────────────────────────────────── */

function shell({ key, name, cfg, assets = {}, inner, timeout = 15000 }) {
  const j = (v) => JSON.stringify(v);
  return [
    "// " + name + " — generated by tools/anim-studio/lib/dungeon-templates.js",
    "// Re-run tools/safe-edit/bin/_build-dungeon-animations.js to regenerate.",
    "(async () => {",
    "",
    "const CFG = " + j(cfg) + ";",
    "const ASSETS = " + j(assets) + ";",
    "const ANIM_KEY = " + j("oni.dungeon." + key) + ";",
    "const TAG = " + j("[ONI][Anim][" + name + "]") + ";",
    "",
    "const P = globalThis.__PAYLOAD ?? payload ?? {};",
    "function tokFromUuid(u) { try { const d = fromUuidSync?.(u); return d?.object ?? null; } catch (_) { return null; } }",
    "function resolveSource() {",
    "  for (const c of [P?.casterTokenUuid, P?.sourceTokenUuid, P?.tokenUuid]) { const t = tokFromUuid(c); if (t) return t; }",
    "  return canvas?.tokens?.controlled?.[0] ?? null;",
    "}",
    "function resolveTargets() {",
    "  const out = [];",
    "  const arg = Array.isArray(targets) ? targets : [];",
    "  for (const t of arg) if (t?.center) out.push(t);",
    "  if (!out.length && Array.isArray(globalThis.__TARGETS)) for (const t of globalThis.__TARGETS) if (t?.center) out.push(t);",
    "  return out;",
    "}",
    "const sourceToken  = resolveSource();",
    "const partyTargets = resolveTargets();",
    "",
    "const doneHook = 'oni.anim.' + ANIM_KEY + '.' + (foundry?.utils?.randomID?.(8) ?? String(Date.now()));",
    "function onceHook(hookName, timeoutMs) {",
    "  return new Promise((resolve) => {",
    "    let settled = false;",
    "    const timer = setTimeout(() => { if (settled) return; settled = true; Hooks.off(hookName, h); resolve({ ok: false, timeout: true }); }, timeoutMs);",
    "    const h = (d) => { if (settled) return; settled = true; clearTimeout(timer); Hooks.off(hookName, h); resolve(d ?? { ok: true }); };",
    "    Hooks.on(hookName, h);",
    "  });",
    "}",
    "function emitLocal(n, d) { try { Hooks.callAll(n, d); } catch (_) {} }",
    "",
    "const scriptSource = String.raw`",
    inner,
    "`;",
    "",
    "try {",
    "  emitLocal('oni:animationStart', { type: ANIM_KEY, sceneId: canvas.scene?.id ?? null });",
    // Register the gate listener BEFORE broadcasting, or a fast inner script can
    // fire doneHook before anyone is listening and the sequence hangs to timeout.
    "  const waitDone = onceHook(doneHook, CFG.totalTimeoutMs || " + timeout + ");",
    "  await game.ONI.pseudo.play({",
    "    scriptId: ANIM_KEY,",
    "    scriptSource,",
    "    casterTokenUuid: sourceToken?.document?.uuid ?? null,",
    "    targetTokenUuids: partyTargets.map(t => t.document.uuid),",
    "    params: { doneHook, cfg: CFG, assets: ASSETS },",
    "    meta: { source: " + j(name) + " },",
    "  });",
    "  const result = await waitDone;",
    "  if (!result?.ok) console.warn(TAG, 'pseudo non-OK / timeout', result);",
    "} catch (err) {",
    "  console.error(TAG, 'orchestration crashed', err);",
    "} finally {",
    "  emitLocal('oni:animationEnd', { type: ANIM_KEY, timestamp: Date.now() });",
    "}",
    "",
    "})();",
  ].join("\n");
}

/* ── Inner preamble, shared by every template ───────────────────────────── */
//
// screenLive() (not screen()) everywhere: it re-reads the world transform on
// each access, so overlays survive a camera move. Costs nothing when the camera
// is still, and removes a whole class of "why did the dim slide off" bugs.

const PRE = [
  "const cfg = ctx.params.cfg || {};",
  "const A = ctx.params.assets || {};",
  "const caster = ctx.casterToken;",
  "const tgts = (ctx.targetTokens || []).filter(t => t && t.center);",
  "const prime = tgts[0] || null;",
  "const S = oni.screenLive();",
  "const E = oni.EASE;",
  "const ctr = (t) => (t && t.center) ? t.center : { x: 0, y: 0 };",
  "const home = caster ? { x: caster.center.x, y: caster.center.y } : { x: 0, y: 0 };",
  "function centroid(list) {",
  "  if (!list.length) return home;",
  "  let x = 0, y = 0;",
  "  for (const t of list) { const c = ctr(t); x += c.x; y += c.y; }",
  "  return { x: x / list.length, y: y / list.length };",
  "}",
  "function playSfx(k, v) { if (cfg[k]) oni.sfx(cfg[k], { volume: cfg[v] == null ? 0.6 : cfg[v] }); }",
  "let fired = false;",
  "function done() { if (fired) return; fired = true; oni.fireDone(); }",
  // Shake a clone of the target rather than the token itself: moving a real
  // placeable mid-animation fights Foundry's own refresh and can desync
  // positions. The clone is disposed with the rest of the run.
  "async function shakeTarget(t, ms, amp) {",
  "  if (!t) return;",
  "  const spr = oni.cloneToken(t);",
  "  if (!spr) return;",
  "  const restore = oni.hideToken(t);",
  "  const c = ctr(t);",
  "  await oni.tween({ from: 0, to: 1, duration: ms, ease: E.linear, onUpdate: (v) => {",
  "    const decay = 1 - v;",
  "    spr.position.set(c.x + (Math.random() * 2 - 1) * amp * decay, c.y + (Math.random() * 2 - 1) * amp * decay);",
  "  } });",
  "  spr.position.set(c.x, c.y);",
  "  restore();",
  "  try { spr.destroy(); } catch (e) {}",
  "}",
  // Additive tapered streak, used as the generic slash / beam mark.
  "function streak(x1, y1, x2, y2, color, width, host) {",
  "  const g = new PIXI.Graphics();",
  "  g.lineStyle({ width: width, color: color, alpha: 1, cap: 'round' });",
  "  g.moveTo(x1, y1); g.lineTo(x2, y2);",
  "  g.blendMode = PIXI.BLEND_MODES.ADD;",
  "  (host || canvas.stage).addChild(g);",
  "  return g;",
  "}",
].join("\n");

function inner(body) {
  return PRE + "\n\n" + body;
}

/* ── T1 · generic melee ──────────────────────────────────────────────────── */
//
// Clone lunges to the target, a bright streak crosses it, the target clone
// shakes, embers pop, the clone slides home. The workhorse: every plain
// "Deal Physical damage to one creature" row in the pass uses this.

function melee(opts = {}) {
  const cfg = Object.assign({
    color: 0xffe9c4, slashColor: 0xffffff, slashWidth: 9,
    lungeMs: 420, holdMs: 90, returnMs: 520,
    standoff: 0.62, shakeMs: 460, shakeAmp: 9,
    particles: 18, particleRadius: 120, particleSize: 11,
    slashCount: 2, slashGapMs: 110, slashFadeMs: 300,
    donePhase: "end",
    sfx: null, sfxVol: 0.6, sfxImpact: null, sfxImpactVol: 0.7,
    totalTimeoutMs: 12000,
  }, opts.cfg || {});

  const body = [
    "if (!caster || !prime) { done(); return; }",
    "const host = oni.layer({ zIndex: 93000 });",
    "const t = ctr(prime);",
    "const dx = t.x - home.x, dy = t.y - home.y;",
    "const land = { x: home.x + dx * cfg.standoff, y: home.y + dy * cfg.standoff };",
    "",
    "const clone = oni.cloneToken(caster, { parent: host });",
    "const restoreCaster = oni.hideToken(caster);",
    "playSfx('sfx', 'sfxVol');",
    "",
    "await oni.tween({ from: 0, to: 1, duration: cfg.lungeMs, ease: E.inOutQuad, onUpdate: (v) => {",
    "  if (clone) clone.position.set(home.x + (land.x - home.x) * v, home.y + (land.y - home.y) * v);",
    "} });",
    "",
    "playSfx('sfxImpact', 'sfxImpactVol');",
    "const perp = Math.atan2(dy, dx) + Math.PI / 2;",
    "const len = S.wLen(90);",
    "for (let i = 0; i < cfg.slashCount; i++) {",
    "  const off = (i - (cfg.slashCount - 1) / 2) * S.wLen(26);",
    "  const ox = Math.cos(perp + Math.PI / 2) * off, oy = Math.sin(perp + Math.PI / 2) * off;",
    "  const g = streak(",
    "    t.x + Math.cos(perp) * len + ox, t.y + Math.sin(perp) * len + oy,",
    "    t.x - Math.cos(perp) * len + ox, t.y - Math.sin(perp) * len + oy,",
    "    cfg.slashColor, S.wLen(cfg.slashWidth), host);",
    "  oni.tween({ from: 1, to: 0, duration: cfg.slashFadeMs, ease: E.inQuad, onUpdate: (v) => { g.alpha = v; } });",
    "  if (i < cfg.slashCount - 1) await wait(cfg.slashGapMs);",
    "}",
    "",
    "oni.particles({ x: t.x, y: t.y, count: cfg.particles, color: cfg.color,",
    "  size: cfg.particleSize, radius: S.wLen(cfg.particleRadius), life: 780,",
    "  gravity: S.wLen(40), blend: PIXI.BLEND_MODES.ADD, parent: host });",
    "const shaking = shakeTarget(prime, cfg.shakeMs, S.wLen(cfg.shakeAmp));",
    "if (cfg.donePhase === 'impact') done();",
    "",
    "await wait(cfg.holdMs);",
    "await oni.tween({ from: 0, to: 1, duration: cfg.returnMs, ease: E.inOutQuad, onUpdate: (v) => {",
    "  if (clone) clone.position.set(land.x + (home.x - land.x) * v, land.y + (home.y - land.y) * v);",
    "} });",
    "restoreCaster();",
    "await shaking;",
    "done();",
  ].join("\n");

  return shell({ key: opts.key, name: opts.name, cfg, inner: inner(body) });
}

/* ── T2 · generic ranged ─────────────────────────────────────────────────── */
//
// A glowing additive orb travels caster → each target with a fading dot trail,
// then bursts. Multi-target rows fire the orbs staggered rather than at once,
// which reads as deliberate instead of like a shotgun.

function ranged(opts = {}) {
  const cfg = Object.assign({
    color: 0x9fd8ff, coreColor: 0xffffff,
    travelMs: 620, orbSize: 30, trailEvery: 34, trailLife: 340,
    windupMs: 320, windupCount: 14, windupRadius: 90,
    impactCount: 20, impactRadius: 130, impactSize: 12,
    staggerMs: 130, shakeMs: 380, shakeAmp: 7,
    donePhase: "end",
    sfx: null, sfxVol: 0.55, sfxImpact: null, sfxImpactVol: 0.6,
    totalTimeoutMs: 12000,
  }, opts.cfg || {});

  const body = [
    "if (!caster || !tgts.length) { done(); return; }",
    "const host = oni.layer({ zIndex: 93000 });",
    "const glow = oni.radialTexture('rgba(255,255,255,1)', 'rgba(255,255,255,0)', { size: 128 });",
    "",
    "playSfx('sfx', 'sfxVol');",
    "await oni.particles({ x: home.x, y: home.y, count: cfg.windupCount, color: cfg.color,",
    "  size: 12, radius: S.wLen(cfg.windupRadius), life: cfg.windupMs, mode: 'gather',",
    "  blend: PIXI.BLEND_MODES.ADD, parent: host, ease: E.inQuad });",
    "",
    "async function bolt(target) {",
    "  const t = ctr(target);",
    "  const orb = new PIXI.Sprite(glow);",
    "  orb.anchor.set(0.5);",
    "  orb.width = orb.height = S.wLen(cfg.orbSize);",
    "  orb.tint = cfg.color;",
    "  orb.blendMode = PIXI.BLEND_MODES.ADD;",
    "  orb.position.set(home.x, home.y);",
    "  host.addChild(orb);",
    "  const core = new PIXI.Sprite(glow);",
    "  core.anchor.set(0.5);",
    "  core.width = core.height = S.wLen(cfg.orbSize * 0.45);",
    "  core.tint = cfg.coreColor;",
    "  core.blendMode = PIXI.BLEND_MODES.ADD;",
    "  host.addChild(core);",
    "  let lastTrail = 0;",
    "  await oni.tween({ from: 0, to: 1, duration: cfg.travelMs, ease: E.inOutQuad, onUpdate: (v) => {",
    "    const x = home.x + (t.x - home.x) * v, y = home.y + (t.y - home.y) * v;",
    "    orb.position.set(x, y); core.position.set(x, y);",
    "    const now = performance.now();",
    "    if (now - lastTrail >= cfg.trailEvery) {",
    "      lastTrail = now;",
    "      const d = new PIXI.Sprite(glow);",
    "      d.anchor.set(0.5);",
    "      d.width = d.height = S.wLen(cfg.orbSize * 0.6);",
    "      d.tint = cfg.color;",
    "      d.blendMode = PIXI.BLEND_MODES.ADD;",
    "      d.position.set(x, y);",
    "      host.addChild(d);",
    "      oni.tween({ from: 1, to: 0, duration: cfg.trailLife, ease: E.outQuad, onUpdate: (a) => {",
    "        d.alpha = a; d.scale.set(d.scale.x * 0.995);",
    "      }, onComplete: () => { try { d.destroy(); } catch (e) {} } });",
    "    }",
    "  } });",
    "  try { orb.destroy(); core.destroy(); } catch (e) {}",
    "  playSfx('sfxImpact', 'sfxImpactVol');",
    "  oni.particles({ x: t.x, y: t.y, count: cfg.impactCount, color: cfg.color,",
    "    size: cfg.impactSize, radius: S.wLen(cfg.impactRadius), life: 700,",
    "    blend: PIXI.BLEND_MODES.ADD, parent: host });",
    "  return shakeTarget(target, cfg.shakeMs, S.wLen(cfg.shakeAmp));",
    "}",
    "",
    "const runs = [];",
    "for (let i = 0; i < tgts.length; i++) {",
    "  runs.push(bolt(tgts[i]));",
    "  if (i < tgts.length - 1) await wait(cfg.staggerMs);",
    "}",
    "if (cfg.donePhase === 'impact') done();",
    "await Promise.all(runs);",
    "done();",
  ].join("\n");

  return shell({ key: opts.key, name: opts.name, cfg, inner: inner(body) });
}

/* ── T3 · rush ───────────────────────────────────────────────────────────── */
//
// Dash in, hold, dash back — no slash. The physical-contact beat behind
// Tentacle Grab, Basalt Crush, Strip Weapon/Armor, Draining Kiss and Prank.
// `overlap` 1.0 puts the clone dead on top of the target (Draining Kiss);
// lower values stop it short.

function rush(opts = {}) {
  const cfg = Object.assign({
    dashMs: 460, holdMs: 700, returnMs: 620, overlap: 0.66,
    jitter: 0, jitterAmp: 0, jitterHz: 0,
    impact: true, impactColor: 0xffe9c4, impactCount: 14, impactRadius: 100,
    shakeMs: 360, shakeAmp: 7,
    donePhase: "end",
    sfx: null, sfxVol: 0.6, sfxArrive: null, sfxArriveVol: 0.6,
    totalTimeoutMs: 12000,
  }, opts.cfg || {});

  const body = [
    "if (!caster || !prime) { done(); return; }",
    "const host = oni.layer({ zIndex: 93000 });",
    "const t = ctr(prime);",
    "const land = { x: home.x + (t.x - home.x) * cfg.overlap, y: home.y + (t.y - home.y) * cfg.overlap };",
    "const clone = oni.cloneToken(caster, { parent: host });",
    "const restoreCaster = oni.hideToken(caster);",
    "playSfx('sfx', 'sfxVol');",
    "",
    "await oni.tween({ from: 0, to: 1, duration: cfg.dashMs, ease: E.inOutQuad, onUpdate: (v) => {",
    "  if (clone) clone.position.set(home.x + (land.x - home.x) * v, home.y + (land.y - home.y) * v);",
    "} });",
    "playSfx('sfxArrive', 'sfxArriveVol');",
    "",
    "let shaking = Promise.resolve();",
    "if (cfg.impact) {",
    "  oni.particles({ x: t.x, y: t.y, count: cfg.impactCount, color: cfg.impactColor,",
    "    size: 11, radius: S.wLen(cfg.impactRadius), life: 700,",
    "    blend: PIXI.BLEND_MODES.ADD, parent: host });",
    "  shaking = shakeTarget(prime, cfg.shakeMs, S.wLen(cfg.shakeAmp));",
    "}",
    "if (cfg.donePhase === 'impact') done();",
    "",
    // Optional cartoon jitter while held in place — Prank's whole character.
    "if (cfg.jitter && cfg.holdMs > 0) {",
    "  await oni.tween({ from: 0, to: 1, duration: cfg.holdMs, ease: E.linear, onUpdate: (v) => {",
    "    if (!clone) return;",
    "    const ph = v * cfg.holdMs / 1000 * cfg.jitterHz * Math.PI * 2;",
    "    clone.position.set(land.x + Math.sin(ph) * S.wLen(cfg.jitterAmp), land.y + Math.cos(ph * 1.7) * S.wLen(cfg.jitterAmp * 0.6));",
    "  } });",
    "} else {",
    "  await wait(cfg.holdMs);",
    "}",
    "",
    "await oni.tween({ from: 0, to: 1, duration: cfg.returnMs, ease: E.inOutQuad, onUpdate: (v) => {",
    "  if (clone) clone.position.set(land.x + (home.x - land.x) * v, land.y + (home.y - land.y) * v);",
    "} });",
    "restoreCaster();",
    "await shaking;",
    "done();",
  ].join("\n");

  return shell({ key: opts.key, name: opts.name, cfg, inner: inner(body) });
}

/* ── T4 · drain ──────────────────────────────────────────────────────────── */
//
// Optional pierce arrow, impact, then a particle stream flowing target →
// caster. Mana Stinger, Volt Stinger and Mind Sap are all this shape; the only
// difference between them is colour and whether the caster closes to contact.

function drain(opts = {}) {
  const cfg = Object.assign({
    color: 0x5fa8ff, arrow: true, arrowColor: 0x8ec5ff, arrowMs: 380, arrowLen: 130,
    approach: true, dashMs: 460, overlap: 0.6, returnMs: 620,
    impactCount: 16, impactRadius: 110,
    drainCount: 30, drainMs: 1100, drainStagger: 420, drainSize: 10,
    shakeMs: 400, shakeAmp: 8,
    donePhase: "end",
    sfx: null, sfxVol: 0.6, sfxDrain: null, sfxDrainVol: 0.5,
    totalTimeoutMs: 14000,
  }, opts.cfg || {});

  const body = [
    "if (!caster || !prime) { done(); return; }",
    "const host = oni.layer({ zIndex: 93000 });",
    "const t = ctr(prime);",
    "const land = { x: home.x + (t.x - home.x) * cfg.overlap, y: home.y + (t.y - home.y) * cfg.overlap };",
    "let clone = null, restoreCaster = null;",
    "playSfx('sfx', 'sfxVol');",
    "",
    "if (cfg.approach) {",
    "  clone = oni.cloneToken(caster, { parent: host });",
    "  restoreCaster = oni.hideToken(caster);",
    "  await oni.tween({ from: 0, to: 1, duration: cfg.dashMs, ease: E.inOutQuad, onUpdate: (v) => {",
    "    if (clone) clone.position.set(home.x + (land.x - home.x) * v, home.y + (land.y - home.y) * v);",
    "  } });",
    "}",
    "",
    "const from = cfg.approach ? land : home;",
    "if (cfg.arrow) {",
    "  const ang = Math.atan2(t.y - from.y, t.x - from.x);",
    "  const L = S.wLen(cfg.arrowLen);",
    "  const g = streak(from.x, from.y, from.x, from.y, cfg.arrowColor, S.wLen(10), host);",
    "  await oni.tween({ from: 0, to: 1, duration: cfg.arrowMs, ease: E.outQuad, onUpdate: (v) => {",
    "    const hx = from.x + (t.x - from.x) * v, hy = from.y + (t.y - from.y) * v;",
    "    g.clear();",
    "    g.lineStyle({ width: S.wLen(10), color: cfg.arrowColor, alpha: 1, cap: 'round' });",
    "    g.moveTo(hx - Math.cos(ang) * L, hy - Math.sin(ang) * L);",
    "    g.lineTo(hx, hy);",
    "  } });",
    "  oni.tween({ from: 1, to: 0, duration: 280, ease: E.inQuad, onUpdate: (v) => { g.alpha = v; } });",
    "}",
    "",
    "oni.particles({ x: t.x, y: t.y, count: cfg.impactCount, color: cfg.color,",
    "  size: 11, radius: S.wLen(cfg.impactRadius), life: 640,",
    "  blend: PIXI.BLEND_MODES.ADD, parent: host });",
    "const shaking = shakeTarget(prime, cfg.shakeMs, S.wLen(cfg.shakeAmp));",
    "playSfx('sfxDrain', 'sfxDrainVol');",
    "",
    // The drain itself: particles stream from the target back to wherever the
    // caster actually is (its clone if it closed in, else its home tile).
    "const sink = cfg.approach ? land : home;",
    "const draining = oni.particles({ x: t.x, y: t.y, toX: sink.x, toY: sink.y,",
    "  count: cfg.drainCount, color: cfg.color, size: cfg.drainSize,",
    "  radius: S.wLen(70), life: cfg.drainMs, stagger: cfg.drainStagger, mode: 'stream',",
    "  blend: PIXI.BLEND_MODES.ADD, parent: host, ease: E.inOutQuad });",
    "if (cfg.donePhase === 'impact') done();",
    "await draining;",
    "",
    "if (cfg.approach && clone) {",
    "  await oni.tween({ from: 0, to: 1, duration: cfg.returnMs, ease: E.inOutQuad, onUpdate: (v) => {",
    "    clone.position.set(land.x + (home.x - land.x) * v, land.y + (home.y - land.y) * v);",
    "  } });",
    "}",
    "if (restoreCaster) restoreCaster();",
    "await shaking;",
    "done();",
  ].join("\n");

  return shell({ key: opts.key, name: opts.name, cfg, inner: inner(body) });
}

/* ── T5 · breath ─────────────────────────────────────────────────────────── */
//
// A cone of particles sprays from the caster toward the target centroid,
// widening as it travels, then each target takes a puff and a shake. Mist
// Breath, Flame Breath, Miasma Nova and the payoff half of Stinky Breath.

function breath(opts = {}) {
  const cfg = Object.assign({
    color: 0xbfead6, chargeMs: 700, chargeCount: 20, chargeRadius: 80,
    sprayMs: 1500, sprayCount: 130, sprayStagger: 900,
    coneSpread: 0.55, reach: 1.25, puffCount: 16, puffRadius: 120,
    particleSize: 22, shakeMs: 460, shakeAmp: 8,
    donePhase: "end",
    sfx: null, sfxVol: 0.6, sfxSpray: null, sfxSprayVol: 0.6,
    totalTimeoutMs: 16000,
  }, opts.cfg || {});

  const body = [
    "if (!caster || !tgts.length) { done(); return; }",
    "const host = oni.layer({ zIndex: 93000 });",
    "const mid = centroid(tgts);",
    "const ang = Math.atan2(mid.y - home.y, mid.x - home.x);",
    "const dist = Math.hypot(mid.x - home.x, mid.y - home.y) * cfg.reach;",
    "const mouth = { x: home.x + Math.cos(ang) * S.wLen(40), y: home.y + Math.sin(ang) * S.wLen(40) };",
    "",
    "playSfx('sfx', 'sfxVol');",
    "await oni.particles({ x: mouth.x, y: mouth.y, count: cfg.chargeCount, color: cfg.color,",
    "  size: 14, radius: S.wLen(cfg.chargeRadius), life: cfg.chargeMs, mode: 'gather',",
    "  blend: PIXI.BLEND_MODES.ADD, parent: host, ease: E.inQuad });",
    "",
    "playSfx('sfxSpray', 'sfxSprayVol');",
    "const glow = oni.radialTexture('rgba(255,255,255,1)', 'rgba(255,255,255,0)', { size: 96 });",
    "const puffs = [];",
    "for (let i = 0; i < cfg.sprayCount; i++) {",
    "  const spread = (Math.random() * 2 - 1) * cfg.coneSpread;",
    "  const a = ang + spread;",
    "  const reach = dist * (0.55 + Math.random() * 0.6);",
    "  const p = new PIXI.Sprite(glow);",
    "  p.anchor.set(0.5);",
    "  p.tint = cfg.color;",
    "  p.blendMode = PIXI.BLEND_MODES.ADD;",
    "  p.position.set(mouth.x, mouth.y);",
    "  p.alpha = 0;",
    "  host.addChild(p);",
    "  const life = cfg.sprayMs * (0.7 + Math.random() * 0.5);",
    "  const delay = Math.random() * cfg.sprayStagger;",
    "  const sz = S.wLen(cfg.particleSize) * (0.6 + Math.random() * 0.9);",
    "  puffs.push(wait(delay).then(() => oni.tween({",
    "    from: 0, to: 1, duration: life, ease: E.outQuad, onUpdate: (v) => {",
    "      p.position.set(mouth.x + Math.cos(a) * reach * v, mouth.y + Math.sin(a) * reach * v);",
    // Widen as it travels: a cone reads as a cone because the motes grow, not
    // only because they fan out.
    "      p.width = p.height = sz * (0.35 + v * 1.5);",
    "      p.alpha = v < 0.25 ? v / 0.25 : (1 - (v - 0.25) / 0.75) * 0.9;",
    "    },",
    "    onComplete: () => { try { p.destroy(); } catch (e) {} },",
    "  })));",
    "}",
    "",
    "await wait(Math.min(cfg.sprayMs * 0.55, 900));",
    "const shakes = [];",
    "for (const tk of tgts) {",
    "  const c = ctr(tk);",
    "  oni.particles({ x: c.x, y: c.y, count: cfg.puffCount, color: cfg.color,",
    "    size: 18, radius: S.wLen(cfg.puffRadius), life: 900,",
    "    blend: PIXI.BLEND_MODES.ADD, parent: host });",
    "  shakes.push(shakeTarget(tk, cfg.shakeMs, S.wLen(cfg.shakeAmp)));",
    "}",
    "if (cfg.donePhase === 'impact') done();",
    "await Promise.all(puffs);",
    "await Promise.all(shakes);",
    "done();",
  ].join("\n");

  return shell({ key: opts.key, name: opts.name, cfg, inner: inner(body) });
}

/* ── T6 · burst ──────────────────────────────────────────────────────────── */
//
// Particles radiate from the caster (self-buff, detonation, counter-flash) or
// pop on each target (spread attacks). `ring` adds an expanding additive
// circle, which is what makes Electro Explosion read as a shockwave rather
// than a puff.

function burst(opts = {}) {
  const cfg = Object.assign({
    color: 0xffe75a, at: "caster",
    gatherMs: 0, gatherCount: 16, gatherRadius: 90,
    count: 40, radius: 260, size: 14, life: 950,
    ring: false, ringMs: 900, ringColor: null, ringWidth: 7, ringRadius: 320,
    flash: false, flashColor: "#ffffff", flashAlpha: 0.35,
    shake: false, shakeMs: 0, shakeAmp: 8, screenshakeMs: 0, screenshakeAmp: 6,
    donePhase: "end",
    sfx: null, sfxVol: 0.6,
    totalTimeoutMs: 12000,
  }, opts.cfg || {});

  const body = [
    "if (!caster) { done(); return; }",
    "const host = oni.layer({ zIndex: 93000 });",
    "const spots = cfg.at === 'targets' && tgts.length ? tgts.map(ctr) : [home];",
    "playSfx('sfx', 'sfxVol');",
    "",
    "if (cfg.gatherMs > 0) {",
    "  await Promise.all(spots.map((p) => oni.particles({ x: p.x, y: p.y,",
    "    count: cfg.gatherCount, color: cfg.color, size: 12,",
    "    radius: S.wLen(cfg.gatherRadius), life: cfg.gatherMs, mode: 'gather',",
    "    blend: PIXI.BLEND_MODES.ADD, parent: host, ease: E.inQuad })));",
    "}",
    "",
    "if (cfg.flash) oni.domFlash({ color: cfg.flashColor, alpha: cfg.flashAlpha, fadeIn: 120, hold: 60, fadeOut: 380 });",
    "if (cfg.screenshakeMs > 0) oni.screenshake({ duration: cfg.screenshakeMs, intensity: cfg.screenshakeAmp });",
    "",
    "const rings = [];",
    "if (cfg.ring) {",
    "  for (const p of spots) {",
    "    const g = new PIXI.Graphics();",
    "    g.blendMode = PIXI.BLEND_MODES.ADD;",
    "    host.addChild(g);",
    "    const col = cfg.ringColor == null ? cfg.color : cfg.ringColor;",
    "    rings.push(oni.tween({ from: 0, to: 1, duration: cfg.ringMs, ease: E.outQuad, onUpdate: (v) => {",
    "      g.clear();",
    "      g.lineStyle({ width: S.wLen(cfg.ringWidth) * (1 - v * 0.6), color: col, alpha: 1 - v });",
    "      g.drawCircle(p.x, p.y, S.wLen(cfg.ringRadius) * v);",
    "    }, onComplete: () => { try { g.destroy(); } catch (e) {} } }));",
    "  }",
    "}",
    "",
    "const bursts = spots.map((p) => oni.particles({ x: p.x, y: p.y,",
    "  count: cfg.count, color: cfg.color, size: cfg.size,",
    "  radius: S.wLen(cfg.radius), life: cfg.life,",
    "  blend: PIXI.BLEND_MODES.ADD, parent: host }));",
    "",
    "const shakes = [];",
    "if (cfg.shake && cfg.shakeMs > 0) for (const tk of tgts) shakes.push(shakeTarget(tk, cfg.shakeMs, S.wLen(cfg.shakeAmp)));",
    "if (cfg.donePhase === 'impact') done();",
    "await Promise.all(rings.concat(bursts, shakes));",
    "done();",
  ].join("\n");

  return shell({ key: opts.key, name: opts.name, cfg, inner: inner(body) });
}


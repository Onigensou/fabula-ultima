function setupFor(entry, old = {}) {
  const lines = {};
  for (const f of LINE_FIELDS) lines[f] = String(old?.[f] ?? "").trim() ? old[f] : (entry.lines?.[f] ?? "");
  return { ...(old || {}), teams: [entry.deck], prizes: entry.prizes, prize: entry.prizes[0] ?? null, diff: entry.diff, style: old?.style ?? null,
    bestOf: [1, 3, 5].includes(Number(old?.bestOf)) ? Number(old.bestOf) : 1, requiresSwitch: UNLOCK, ...lines };
}

export async function migrate(game, log = () => {}) {
  const out = []; let a = 0, tk = 0;
  for (const e of DATA.actors) {
    const actor = game.actors.get(e.id);
    if (!actor) { out.push(`! ${e.name}: actor not found`); continue; }
    await actor.update({ [`flags.${MODULE_ID}.${FLAG}`]: setupFor(e, actor.getFlag(MODULE_ID, FLAG)) });
    a++; out.push(`~ ${e.name}`);
  }
  for (const e of DATA.tokens) {
    // every scene with that name (a town can have one scene per story state with the same name, e.g. Eisendrache Kingdom)
    const tokens = game.scenes.filter((s) => s.name === e.scene).flatMap((s) => s.tokens.filter((t) => t.name === e.name));
    if (!tokens.length) { out.push(`! ${e.scene} / ${e.name}: token not found`); continue; }
    for (const t of tokens) { await t.update({ [`flags.${MODULE_ID}.${FLAG}`]: setupFor(e, t.getFlag(MODULE_ID, FLAG)) }); tk++; }
    out.push(`~ ${e.scene} / ${e.name}${tokens.length > 1 ? ` (${tokens.length} tokens)` : ""}`);
  }
  for (const l of out) log(l);
  const summary = `${a} NPC actors and ${tk} tokens set up as duelists${out.some((l) => l.startsWith("!")) ? "; some not found (see log)" : ""}`;
  log(summary);
  return { applied: true, summary };
}

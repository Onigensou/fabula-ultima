// ── Steps ────────────────────────────────────────────────────────────────────
async function reworkSonicKatar(out) {
  const katar = game.items.get(KATAR);
  if (!katar) { out.push("! Sonic Katar missing"); return; }
  if (katar.getFlag(M, FLAG)) { out.push("= Sonic Katar already reworked"); return; }
  await katar.update({
    "system.props.description": KATAR_TEXT,
    [`system.props.related_item_list.${KATAR_PSV}.related_item_description`]: KATAR_TEXT,
    [`system.props.item_skill_passive.${KATAR_PSV}.skill_description`]: KATAR_TEXT,
  });
  if (await safeDelete(katar, "ActiveEffect", KATAR_MULTI_AE)) out.push("- Sonic Katar: old 'Sonic Blow (Attacks)' effect");
  const sb = game.items.get(SONIC_BLOW);
  if (sb) {
    await sb.update({ name: "Sonic Blow", img: SONIC_BLOW_ICON, ...propsPatch(SONIC_BLOW_PROPS), [`flags.${M}.carrierAttack`]: CARRIER });
    if (await safeDelete(sb, "ActiveEffect", SONIC_MARKER_AE)) out.push("- Sonic Blow: old marker effect");
    out.push("~ Sonic Blow: 30 MP carrier attack, chain 8 volley, ×2 shared, crit ×1.5 no Opportunity, Perfect ×1.5");
  } else out.push("! Sonic Blow (contained) missing");
  const psv = game.items.get(KATAR_PSV);
  if (psv) { await psv.update(propsPatch(KATAR_PSV_PROPS)); out.push("~ Sonic Katar (Passive): rows cleared, text mirrored"); }
  await katar.setFlag(M, FLAG, true);
  out.push("~ Sonic Katar: text");
}

async function reworkGunblade(out) {
  const gb = game.items.get(GUNBLADE);
  if (!gb) { out.push("! Imperial Gunblade missing"); return; }
  await createIfMissing(gbPassiveData(), out);
  await createIfMissing(gbTransformData(), out);
  if (gb.getFlag(M, FLAG)) { out.push("= Gunblade already reworked"); return; }
  await gb.update({
    name: "Gunblade", img: GUNBLADE_ICON, ...propsPatch(GUNBLADE_PROPS),
    [`flags.${M}.weaponForms`]: FORMS, [`flags.${M}.activeForm`]: 0,
  });
  await gb.setFlag(M, FLAG, true);
  out.push("~ Imperial Gunblade → Gunblade: Uncommon 1800z, Sword DEX+MIG HR+8 / Firearm DEX+INS HR+5, odd → +10 Fire, transform before or after");
}

// Actor copies (incl. unlinked token deltas via game.actors' synthetic tokens on scenes).
function* actorsWithItems() {
  for (const a of game.actors ?? []) yield a;
  for (const s of game.scenes ?? []) for (const t of s.tokens ?? []) if (!t.actorLink && t.actor) yield t.actor;
}
async function updateActorCopies(out) {
  const katarKids = [SONIC_BLOW, KATAR_PSV].map((i) => game.items.get(i)).filter(Boolean);
  const gbKids = [ID.gbPassive, ID.gbTransform].map((i) => game.items.get(i)).filter(Boolean);
  let n = 0;
  for (const a of actorsWithItems()) {
    for (const copy of a.items.filter((i) => i.name === "Sonic Katar" && !i.system?.container)) {
      if (copy.getFlag(M, FLAG)) continue;
      await copy.update({ "system.props.description": KATAR_TEXT });
      await safeDelete(copy, "ActiveEffect", copy.effects.find((e) => e.name === "Sonic Blow (Attacks)")?.id);
      for (const child of a.items.filter((i) => i.system?.container === copy.id)) {
        if (child.name === "Sonic Blow") {
          await child.update({ img: SONIC_BLOW_ICON, ...propsPatch(SONIC_BLOW_PROPS), [`flags.${M}.carrierAttack`]: CARRIER });
          await safeDelete(child, "ActiveEffect", child.effects.find((e) => e.name === "Sonic Blow")?.id);
        } else if (child.name === "Sonic Katar (Passive)") await child.update(propsPatch(KATAR_PSV_PROPS));
      }
      for (const c of katarKids) {
        if (a.items.some((i) => i.system?.container === copy.id && i.name === c.name)) continue;
        const cd = c.toObject(); delete cd._id; cd.system.container = copy.id;
        await a.createEmbeddedDocuments("Item", [cd]);
      }
      await copy.setFlag(M, FLAG, true); n++; out.push(`~ ${a.name}: Sonic Katar copy reworked`);
    }
    for (const copy of a.items.filter((i) => (i.name === "Imperial Gunblade" || i.name === "Gunblade") && !i.system?.container)) {
      if (copy.getFlag(M, FLAG)) continue;
      await copy.update({ name: "Gunblade", img: GUNBLADE_ICON, ...propsPatch(GUNBLADE_PROPS), [`flags.${M}.weaponForms`]: FORMS, [`flags.${M}.activeForm`]: 0 });
      for (const c of gbKids) {
        if (a.items.some((i) => i.system?.container === copy.id && i.name === c.name)) continue;
        const cd = c.toObject(); delete cd._id; cd.system.container = copy.id;
        await a.createEmbeddedDocuments("Item", [cd]);
      }
      await copy.setFlag(M, FLAG, true); n++; out.push(`~ ${a.name}: Gunblade copy reworked`);
    }
  }
  if (!n) out.push("= no actor copies of Sonic Katar / Imperial Gunblade");
}

export async function migrate(game, log = () => {}) {
  const out = [];
  await reworkSonicKatar(out);
  await reworkGunblade(out);
  await updateActorCopies(out);
  for (const l of out) log(l);
  return { applied: true, summary: out.join(" | ") };
}

// ── Helpers (Lionheart migration pattern) ────────────────────────────────────
function cloneData(srcId, { id, name, container = null, img, props = {}, effects, folderOf } = {}) {
  const src = game.items.get(srcId);
  if (!src) throw new Error(`donor ${srcId} missing`);
  const d = src.toObject();
  d._id = id;
  d.name = name;
  if (img) d.img = img;
  d.folder = game.items.get(folderOf)?.folder?.id ?? d.folder ?? null;
  d.system.container = container;
  d.system.uniqueId = id;
  d.system.props = { ...d.system.props, ...props, name, id, uuid: `Item.${id}` };
  if (img) d.system.props.img = img;
  if (effects !== undefined) d.effects = effects;
  d.flags = { ...(d.flags ?? {}), [M]: { ...(d.flags?.[M] ?? {}), [FLAG]: "created" } };
  delete d.flags[M].draftAutomation;
  delete d._stats; delete d.sort; delete d.ownership;
  return d;
}
async function createIfMissing(data, out) {
  if (game.items.get(data._id)) { out.push(`= ${data.name} exists`); return game.items.get(data._id); }
  const [doc] = await Item.createDocuments([data], { keepId: true });
  out.push(`+ ${data.name} (${data._id})`);
  return doc;
}
const propsPatch = (props) => Object.fromEntries(Object.entries(props).map(([k, v]) => [`system.props.${k}`, v]));

// Embedded deletes tolerant of the V12 orphaned-embed quirk (Lionheart / Hako pattern):
// skip ids the document does not list, swallow "does not exist" from the server.
async function safeDelete(parent, embeddedName, id) {
  const coll = embeddedName === "Item" ? parent.items : parent.effects;
  if (!coll?.get?.(id)) return false;
  const orig = ui?.notifications?.error?.bind(ui.notifications);
  if (ui?.notifications) ui.notifications.error = (msg, ...rest) => { if (typeof msg === "string" && msg.includes("does not exist")) return; return orig?.(msg, ...rest); };
  try { await parent.deleteEmbeddedDocuments(embeddedName, [id]); return true; }
  catch (e) { if (!/does not exist/i.test(String(e?.message ?? e))) throw e; return false; }
  finally { if (ui?.notifications) ui.notifications.error = orig; }
}

